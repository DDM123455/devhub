// Regenerates src/lib/iso-data/*.ts. Download these files into one folder first (public datasets, no account needed):
//   country-codes.csv   https://raw.githubusercontent.com/datasets/country-codes/main/data/country-codes.csv
//   codes-all.csv       https://raw.githubusercontent.com/datasets/currency-codes/main/data/codes-all.csv
//   language-codes-full.csv  https://raw.githubusercontent.com/datasets/language-codes/main/data/language-codes-full.csv
//   registry.txt        https://raw.githubusercontent.com/globalcitizen/php-iban/master/registry.txt
// then run: node scripts/gen-iso-data.cjs <that folder>. The output is committed, so this is only needed to refresh it.
// Generates src/lib/iso-data/*.ts from public datasets (datasets/country-codes, datasets/currency-codes,
// datasets/language-codes, globalcitizen/php-iban registry). Run once; the output is committed.
const fs = require('fs');
const path = require('path');
const SRC = process.argv[2];
if (!SRC) {
	console.error('usage: node scripts/gen-iso-data.cjs <dir with the downloaded datasets>');
	process.exit(1);
}
const OUT = path.join(__dirname, '..', 'src', 'lib', 'iso-data');
fs.mkdirSync(OUT, { recursive: true });

function parseCsv(text) {
	const rows = [];
	let row = [], field = '', q = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (q) {
			if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; }
			else field += c;
		} else if (c === '"') q = true;
		else if (c === ',') { row.push(field); field = ''; }
		else if (c === '\n') { row.push(field.replace(/\r$/, '')); rows.push(row); row = []; field = ''; }
		else field += c;
	}
	if (field || row.length) { row.push(field.replace(/\r$/, '')); rows.push(row); }
	return rows;
}
const header = (u) => `// AUTO-GENERATED by scripts/gen-iso-data (see PROGRESS.md, Phase 3.23). ${u}\n// Reference data only — codes are facts, the lists come from the public datasets named below.\n`;
const q = (s) => JSON.stringify(s);

// ---- countries (ISO 3166-1)
{
	const rows = parseCsv(fs.readFileSync(path.join(SRC, 'country-codes.csv'), 'utf8'));
	const h = rows[0];
	const col = (n) => h.indexOf(n);
	const a2 = col('ISO3166-1-Alpha-2'), a3 = col('ISO3166-1-Alpha-3'), num = col('ISO3166-1-numeric');
	const cldr = col('CLDR display name'), off = col('official_name_en');
	const list = [];
	for (const r of rows.slice(1)) {
		if (!r[a2] || !r[a3] || !r[num]) continue;
		list.push([r[a2], r[a3], r[num].padStart(3, '0'), r[off] || r[cldr] || r[a2]]);
	}
	list.sort((a, b) => a[0].localeCompare(b[0]));
	const body = list.map((x) => `\t[${x.map(q).join(', ')}],`).join('\n');
	fs.writeFileSync(path.join(OUT, 'countries.ts'), header('Source: datasets/country-codes (ISO 3166-1).') +
		`/** [alpha-2, alpha-3, numeric, English short name] */\nexport const COUNTRIES: ReadonlyArray<readonly [string, string, string, string]> = [\n${body}\n];\n`);
	console.log('countries', list.length);
}

// ---- currencies (ISO 4217)
{
	const rows = parseCsv(fs.readFileSync(path.join(SRC, 'codes-all.csv'), 'utf8'));
	const map = new Map();
	for (const r of rows.slice(1)) {
		const [entity, name, code, numeric, minor, withdrawn] = r;
		if (!code || !/^[A-Z]{3}$/.test(code)) continue;
		const cur = map.get(code);
		const rec = cur || { code, numeric: (numeric || '').padStart(3, '0'), name, minor: minor === 'N.A.' || minor === '' ? null : Number(minor), withdrawn: !!withdrawn, entities: [] };
		if (!withdrawn) rec.withdrawn = false;
		if (rec.entities.length < 3) rec.entities.push(entity);
		map.set(code, rec);
	}
	const list = [...map.values()].sort((a, b) => a.code.localeCompare(b.code));
	const body = list.map((c) => `\t[${q(c.code)}, ${q(c.numeric)}, ${q(c.name)}, ${c.minor === null ? 'null' : c.minor}, ${c.withdrawn ? 1 : 0}],`).join('\n');
	fs.writeFileSync(path.join(OUT, 'currencies.ts'), header('Source: datasets/currency-codes (ISO 4217 list one/list three).') +
		`/** [alphabetic code, numeric, currency name, minor units (null = n/a), 1 if withdrawn] */\nexport const CURRENCIES: ReadonlyArray<readonly [string, string, string, number | null, 0 | 1]> = [\n${body}\n];\n`);
	console.log('currencies', list.length);
}

// ---- languages (ISO 639-1/-2)
{
	const rows = parseCsv(fs.readFileSync(path.join(SRC, 'language-codes-full.csv'), 'utf8'));
	const list = rows.slice(1).filter((r) => r[0]).map((r) => [r[2] || '', r[0], r[1] || '', (r[3] || '').split(';')[0].trim()]);
	list.sort((a, b) => (a[1] || '').localeCompare(b[1] || ''));
	const body = list.map((x) => `\t[${x.map(q).join(', ')}],`).join('\n');
	fs.writeFileSync(path.join(OUT, 'languages.ts'), header('Source: datasets/language-codes (ISO 639-1, ISO 639-2).') +
		`/** [639-1 (2 letters or ''), 639-2/B, 639-2/T (or '' when equal to /B), English name] */\nexport const LANGUAGES: ReadonlyArray<readonly [string, string, string, string]> = [\n${body}\n];\n`);
	console.log('languages', list.length);
}

// ---- IBAN registry
{
	const lines = fs.readFileSync(path.join(SRC, 'registry.txt'), 'utf8').split(/\r?\n/).filter(Boolean);
	const h = lines[0].split('|');
	const ix = (n) => h.indexOf(n);
	const list = [];
	for (const line of lines.slice(1)) {
		const f = line.split('|');
		const cc = f[ix('country_code')];
		if (!/^[A-Z]{2}$/.test(cc)) continue;
		list.push({ cc, name: f[ix('country_name')], len: Number(f[ix('iban_length')]), re: f[ix('bban_format_regex')], example: f[ix('iban_example')], official: f[ix('swift_official')] === '1' ? 1 : 0, sepa: f[ix('country_sepa')] === '1' ? 1 : 0 });
	}
	list.sort((a, b) => a.cc.localeCompare(b.cc));
	const body = list.map((x) => `\t{ cc: ${q(x.cc)}, name: ${q(x.name)}, length: ${x.len}, bban: ${q(x.re)}, example: ${q(x.example)}, official: ${x.official}, sepa: ${x.sepa} },`).join('\n');
	fs.writeFileSync(path.join(OUT, 'iban-registry.ts'), header('Source: globalcitizen/php-iban registry (mirrors the SWIFT IBAN registry).') +
		`export interface IbanCountry {\n\tcc: string;\n\tname: string;\n\t/** total IBAN length */\n\tlength: number;\n\t/** regex for the BBAN part (everything after the 4-character prefix), anchored */\n\tbban: string;\n\texample: string;\n\t/** 1 = listed in the official SWIFT registry; 0 = IBAN used but not (yet) official */\n\tofficial: 0 | 1;\n\tsepa: 0 | 1;\n}\n\nexport const IBAN_COUNTRIES: ReadonlyArray<IbanCountry> = [\n${body}\n];\n`);
	console.log('iban', list.length, 'official', list.filter((x) => x.official).length);
}
