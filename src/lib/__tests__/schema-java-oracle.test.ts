import { describe, it, expect } from "vitest";
import { parseSql } from "../schema-java/sql-parser";
import { generate } from "../schema-java/generate";
import { defaults } from "../schema-java/model";
const ddl = `CREATE TABLE customers (
 id NUMBER(18,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 2) PRIMARY KEY,
 full_name VARCHAR2(100 CHAR) NOT NULL,
 amount NUMBER(15,2) DEFAULT 0 NOT NULL,
 created_at DATE DEFAULT SYSDATE,
 updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP,
 content CLOB, photo BLOB, token RAW(16),
 CONSTRAINT uq_customer UNIQUE(full_name),
 CONSTRAINT ck_amount CHECK(amount >= 0)
);
COMMENT ON TABLE customers IS 'Customers';
COMMENT ON COLUMN customers.full_name IS 'Name, surname';
CREATE INDEX ix_customer_date ON customers(created_at);`;
const opts = { ...defaults, dialect: "oracle" as const };
describe("Oracle dedicated DDL adapter", () => {
  it("preserves quoted Oracle names and LOB mapping in JPA output", () => {
    const m = parseSql(
      'CREATE TABLE "Order" ("Id" NUMBER(18) PRIMARY KEY, "text" CLOB);',
      "oracle",
    );
    const java = generate(m, "entity", opts).files[0].content;
    expect(java).toContain('@Table(name = "\\"Order\\"")');
    expect(java).toContain('@Column(name = "\\"text\\""');
    expect(java).toContain("@Lob");
  });
  it("preserves national/fixed-width strings and FLOAT binary precision", () => {
    const m = parseSql(
      "CREATE TABLE t (id NUMBER(18) PRIMARY KEY, title NVARCHAR2(100), code CHAR(4 BYTE), note NCLOB, value FLOAT(126));",
      "oracle",
    );
    const r = generate(m, "sql", opts);
    expect(r.files[0].content).toContain("NVARCHAR2(100)");
    expect(r.files[0].content).toContain("CHAR(4 BYTE)");
    expect(r.files[0].content).toContain("NCLOB");
    expect(r.files[0].content).toContain("FLOAT(126)");
    expect(
      parseSql(r.files[0].content, "oracle").diagnostics.filter(
        (d) => d.severity === "error",
      ),
    ).toEqual([]);
  });
  it("maps native types without losing decimal/time semantics", () => {
    const m = parseSql(ddl, "oracle");
    expect(m.diagnostics.filter((d) => d.severity === "error")).toEqual([]);
    expect(m.tables[0].columns.map((c) => c.javaType)).toEqual([
      "Long",
      "String",
      "BigDecimal",
      "LocalDateTime",
      "OffsetDateTime",
      "String",
      "byte[]",
      "byte[]",
    ]);
    expect(m.tables[0].columns[0].unknown.identitySeed).toBe(10);
    expect(m.tables[0].columns[1].comment).toBe("Name, surname");
    for (const output of ["entity", "dto", "record", "projection"] as const)
      expect(generate(m, output, opts).files).toHaveLength(1);
  });
  it("round-trips supported table metadata through native Oracle SQL", () => {
    const m = parseSql(ddl, "oracle");
    const r = generate(m, "sql", opts);
    expect(r.files, JSON.stringify(r.diagnostics)).toHaveLength(1);
    expect(r.files[0].content).toContain(
      "NUMBER(18,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 2)",
    );
    const back = parseSql(r.files[0].content, "oracle");
    expect(
      back.diagnostics.filter((d) => d.severity === "error"),
      r.files[0].content,
    ).toEqual([]);
    const cols = (x: typeof m) =>
      x.tables[0].columns.map((c) => [
        c.name,
        c.sqlType,
        c.javaType,
        c.length,
        c.precision,
        c.scale,
        c.nullable,
        c.primaryKey,
        c.identity,
        c.default,
        c.comment,
      ]);
    expect(cols(back)).toEqual(cols(m));
    expect(
      back.tables[0].constraints.filter((c) => c.kind !== "primary"),
    ).toEqual(m.tables[0].constraints.filter((c) => c.kind !== "primary"));
  });
  it("handles quoted identifiers, escaped comments and nested commas", () => {
    const m = parseSql(
      `CREATE TABLE "Order" ("class" NUMBER(9) PRIMARY KEY, "user-name" VARCHAR2(80 BYTE) DEFAULT concat('a,b', substr('xyz',1,2))); COMMENT ON COLUMN "Order"."user-name" IS 'It''s a name';`,
      "oracle",
    );
    expect(m.diagnostics.filter((d) => d.severity === "error")).toEqual([]);
    expect(m.tables[0].name).toBe("Order");
    expect(m.tables[0].columns[1].default).toBe(
      "concat('a,b', substr('xyz',1,2))",
    );
    expect(m.tables[0].columns[1].comment).toBe("It's a name");
  });
  it("supports q-quoted strings, composite PK, explicit FK and DEFAULT ON NULL", () => {
    const m = parseSql(
      `CREATE TABLE t (a NUMBER(9), b NUMBER(9), label VARCHAR2(50) DEFAULT ON NULL q'[a,b('x')]', PRIMARY KEY(a,b), FOREIGN KEY(a) REFERENCES parent(id));`,
      "oracle",
    );
    expect(m.diagnostics.filter((d) => d.severity === "error")).toEqual([]);
    expect(m.tables[0].columns[2].unknown.defaultOnNull).toBe(true);
    expect(generate(m, "entity", opts).files[0].content).toContain("@IdClass");
  });
  it("identity modes retain their meaning", () => {
    for (const mode of ["ALWAYS", "BY DEFAULT", "BY DEFAULT ON NULL"]) {
      const m = parseSql(
        `CREATE TABLE t (id NUMBER(18) GENERATED ${mode} AS IDENTITY PRIMARY KEY);`,
        "oracle",
      );
      const r = generate(m, "sql", opts);
      expect(r.files[0].content).toContain(`GENERATED ${mode} AS IDENTITY`);
    }
  });
  it("cross-dialect output uses Oracle types and portable numeric capacity", () => {
    const m = parseSql(
      "CREATE TABLE t (id BIGINT PRIMARY KEY, name VARCHAR(60), balance DECIMAL(12,2), created_at TIMESTAMP);",
      "mysql",
    );
    const r = generate(m, "sql", opts);
    expect(r.files[0].content).toContain("NUMBER(19,0)");
    expect(r.files[0].content).toContain("VARCHAR2(60 CHAR)");
    expect(
      parseSql(r.files[0].content, "oracle").diagnostics.filter(
        (d) => d.severity === "error",
      ),
    ).toEqual([]);
  });
  it("rejects unsupported Oracle syntax instead of silently dropping it", () => {
    for (const sql of [
      "CREATE SEQUENCE seq;",
      "BEGIN NULL; END;",
      "SELECT * FROM customers;",
      "CREATE TABLE t (id NUMBER) TABLESPACE users;",
      "CREATE TABLE t (id NUMBER GENERATED ALWAYS AS IDENTITY (CACHE 10));",
      "CREATE TABLE t (x XMLTYPE);",
      "CREATE TABLE t (id NUMBER(10,-2));",
      "CREATE TABLE t (a NUMBER,,b NUMBER);",
    ]) {
      expect(
        parseSql(sql, "oracle").diagnostics.some((d) => d.severity === "error"),
        sql,
      ).toBe(true);
    }
  });
  it("reports source locations for malformed Oracle input", () => {
    const m = parseSql("CREATE TABLE t (\n name VARCHAR2(40\n);", "oracle");
    expect(m.diagnostics[0]).toMatchObject({
      severity: "error",
      code: "syntax",
    });
    expect(m.diagnostics[0].line).toBeGreaterThan(0);
  });
});
