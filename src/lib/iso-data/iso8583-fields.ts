// ISO 8583:1987 data element table (DE 2-128). Field names and formats follow the 1987 edition as implemented by the
// common ASCII/BCD packagers; later editions (1993, 2003) reuse most numbers but change some lengths, so the
// validator tells the user which edition the MTI announces.
//
//   n   digits            an  letters+digits      ans  letters+digits+specials
//   b   binary (length in BITS)                   z    track data (digits, '=' / 'D' separator)
//   xn  'C' or 'D' followed by digits (amounts with a credit/debit sign)
//
// `lv` is the number of digits of the length indicator: 0 = fixed length, 2 = LLVAR, 3 = LLLVAR.
// For variable fields `len` is the maximum length.

export type Iso8583Type = 'n' | 'an' | 'ans' | 'b' | 'z' | 'xn';

export interface Iso8583Field {
	de: number;
	name: string;
	type: Iso8583Type;
	len: number;
	lv: 0 | 2 | 3;
}

