export function describeField(de: number): string {
	const d = FIELD_DESCRIPTIONS[de];
	if (d) return d;
	if (de >= 105 && de <= 111) return 'Reserved for ISO use.';
	if (de >= 112 && de <= 119) return 'Reserved for national use; the meaning depends on the country or scheme.';
	if (de >= 120 && de <= 127) return 'Reserved for private use; the meaning depends on the network or institution.';
	if (de >= 56 && de <= 59) return 'Reserved for national use.';
	if (de >= 61 && de <= 63) return 'Reserved for private use.';
	return 'Standard data element; see ISO 8583 for its definition.';
}

