import * as pg from "node-sql-parser/build/postgresql";
import * as my from "node-sql-parser/build/mysql";
import * as tsql from "node-sql-parser/build/transactsql";
import * as sqlite from "node-sql-parser/build/sqlite";
import { parserDatabase, isMysql } from "./dialects";
import {
  assignNames,
  checkInput,
  identifier,
  type Column,
  type Dialect,
  type Model,
  type Table,
} from "./model";
import { javaType } from "./types";
import { tokenizeSql, syntaxFor } from "../sql-tokenize";
import { parseOracle } from "./oracle-parser";
// The vendor AST differs between dialects; keep its untyped boundary in this adapter.
type Ast = any;
export function parserFor(d: Dialect): Ast {
  if (d === "oracle") throw new Error("Oracle uses the dedicated DDL parser");
  const m: any =
    d === "postgresql"
      ? pg
      : d === "sqlserver"
        ? tsql
        : d === "sqlite"
          ? sqlite
          : my;
  return new (m.Parser ?? m.default.Parser)();
}
const name = (v: Ast): string =>
  typeof v === "string" ? v : String(v?.expr?.value ?? v?.value ?? "");
const columns = (a: Ast[]): string[] => (a ?? []).map((x) => name(x.column));
export function parseSql(
  input: string,
  dialect: Dialect,
  schema?: Model,
): Model {
  checkInput(input);
  if (dialect === "oracle") return parseOracle(input);
  const p = parserFor(dialect),
    options = { database: parserDatabase(dialect) };
  const model: Model = { version: 1, dialect, tables: [], diagnostics: [] };
  const tokens = tokenizeSql(input, syntaxFor(dialect)).filter(
    (t) => !["ws", "lineComment", "blockComment"].includes(t.type),
  );
  const identityModes: string[] = [];
  const edits: { start: number; end: number }[] = [];
  for (let i = 0; i < tokens.length; i++)
    if (
      dialect === "postgresql" &&
      tokens[i].value.toUpperCase() === "GENERATED"
    ) {
      const words = tokens.slice(i, i + 6).map((t) => t.value.toUpperCase());
      if (words.slice(0, 4).join(" ") === "GENERATED ALWAYS AS IDENTITY") {
        identityModes.push("always");
        edits.push({ start: tokens[i + 1].start, end: tokens[i + 1].end });
      } else if (
        words.slice(0, 6).join(" ") === "GENERATED BY DEFAULT AS IDENTITY"
      )
        identityModes.push("default");
    }
  let normalized = input;
  for (const e of edits.reverse())
    normalized =
      normalized.slice(0, e.start) + "BY DEFAULT" + normalized.slice(e.end);
  let parsed: Ast;
  try {
    parsed = p.astify(normalized, options);
  } catch (e: any) {
    model.diagnostics.push({
      severity: "error",
      code: "syntax",
      detail: e.message,
      line: e.location?.start?.line,
      column: e.location?.start?.column,
    });
    return model;
  }
  let identityIndex = 0;
  const expression = (x: Ast) => p.exprToSQL(x, options);
  const statements: Ast[] = Array.isArray(parsed) ? parsed : [parsed];
  for (const a of statements) {
    if (a.type === "comment" || (a.type === "create" && a.keyword === "index"))
      continue;
    if (a.type === "select") {
      if (a.with || a._next || a.from?.some((f: Ast) => f.expr)) {
        model.diagnostics.push({
          severity: "error",
          code: "unsupported",
          detail: "SELECT CTE / UNION / subquery",
        });
        continue;
      }
      const table: Table = {
        name: "query_result",
        className: "QueryResult",
        columns: [],
        constraints: [],
        source: input,
        unknown: {},
      };
      for (const [i, item] of (a.columns ?? []).entries()) {
        const e = item.expr;
        const original = name(e?.column);
        const alias = name(item.as) || original || `expression_${i + 1}`;
        if (original === "*" || e?.type === "star") {
          model.diagnostics.push({
            severity: "error",
            code: "unsupported",
            detail: "SELECT *: list explicit columns",
          });
          continue;
        }
        const sources = (a.from ?? []).filter(
          (f: Ast) => !e?.table || f.as === e.table || f.table === e.table,
        );
        const candidates = sources.flatMap((f: Ast) =>
          (schema?.tables ?? [])
            .filter((t) => t.name === f.table)
            .flatMap((t) => t.columns.filter((c) => c.name === original)),
        );
        const source =
          e?.type === "column_ref" && candidates.length === 1
            ? candidates[0]
            : undefined;
        const type =
          source?.javaType ??
          (e?.type === "aggr_func" && e.name === "COUNT"
            ? "Long"
            : e?.type === "number"
              ? "BigDecimal"
              : e?.type?.includes("string")
                ? "String"
                : "Object");
        const c: Column = {
          name: alias,
          javaName: identifier(alias),
          sqlType: source?.sqlType ?? "",
          javaType: type,
          nullable: null,
          primaryKey: false,
          selected: true,
          origin: { name: "input", javaType: source ? "input" : "inferred" },
          unknown: { expression: e },
        };
        if (type === "Object")
          model.diagnostics.push({
            severity: "warning",
            code: "unknownType",
            detail: alias,
          });
        if (c.javaName !== alias)
          model.diagnostics.push({
            severity: "warning",
            code: "alias",
            detail: alias + " → " + c.javaName,
          });
        table.columns.push(c);
      }
      assignNames(table);
      model.tables.push(table);
      continue;
    }
    if (a.type !== "create" || a.keyword !== "table" || a.query_expr) {
      model.diagnostics.push({
        severity: "error",
        code: "unsupported",
        detail: a.type + " " + a.keyword,
      });
      continue;
    }
    const ref = a.table[0];
    const t: Table = {
      name: name(ref.table),
      schema: ref.db ? name(ref.db) : undefined,
      className: identifier(name(ref.table), true),
      columns: [],
      constraints: [],
      source: input,
      unknown: { tableOptions: a.table_options },
    };
    for (const def of a.create_definitions ?? []) {
      if (def.resource === "column") {
        const type = def.definition;
        const suffix = (type.suffix ?? []).join(" ");
        const sql =
          type.dataType.toUpperCase() +
          (/^(WITH|WITHOUT) TIME ZONE$/.test(suffix) ? " " + suffix : "");
        const c: Column = {
          name: name(def.column.column),
          javaName: identifier(name(def.column.column)),
          sqlType: sql,
          javaType: javaType(sql),
          nullable: def.primary_key ? false : def.nullable?.type !== "not null",
          primaryKey: !!def.primary_key,
          selected: true,
          origin: {
            name: "input",
            sqlType: "input",
            nullable: "input",
            javaType: "inferred",
          },
          unknown: { definition: def },
        };
        if (/DECIMAL|NUMERIC/.test(sql)) {
          c.precision = type.length;
          c.scale = type.scale;
        } else c.length = type.length;
        c.identity =
          !!def.auto_increment ||
          /SERIAL/.test(sql) ||
          !!def.generated_by_default;
        if (dialect === "sqlserver" && def.auto_increment) {
          c.unknown.identitySeed = def.auto_increment.seed?.value ?? 1;
          c.unknown.identityIncrement =
            def.auto_increment.increment?.value ?? 1;
        }
        if (
          dialect === "sqlserver" &&
          ["TIMESTAMP", "ROWVERSION"].includes(sql)
        )
          c.javaType = "byte[]";
        if (
          dialect === "sqlite" &&
          (c.javaType === "BigDecimal" ||
            c.javaType.startsWith("Local") ||
            c.javaType === "Boolean")
        )
          model.diagnostics.push({
            severity: "warning",
            code: "sqliteAffinity",
            detail: c.name,
          });
        if (def.generated_by_default)
          c.unknown.identityMode = identityModes[identityIndex++] ?? "default";
        if (def.default_val) c.default = expression(def.default_val.value);
        if (def.generated?.expr) c.generated = expression(def.generated.expr);
        if (def.comment) c.comment = String(def.comment.value?.value ?? "");
        if (def.unique)
          t.constraints.push({ kind: "unique", columns: [c.name] });
        if (def.reference_definition) {
          const r = def.reference_definition;
          t.constraints.push({
            kind: "foreign",
            columns: [c.name],
            reference: {
              table: name(r.table[0].table),
              columns: columns(r.definition),
            },
          });
        }
        if (c.javaType === "Object")
          model.diagnostics.push({
            severity: "warning",
            code: "unknownType",
            detail: c.name + ": " + sql,
          });
        if (
          (suffix && !/^(WITH|WITHOUT) TIME ZONE$/.test(suffix)) ||
          type.array ||
          sql === "ENUM"
        )
          model.diagnostics.push({
            severity: "warning",
            code: "unsupportedMetadata",
            detail: c.name,
          });
        t.columns.push(c);
        continue;
      }
      const kind = String(
        def.constraint_type ?? def.keyword ?? "",
      ).toLowerCase();
      const c: any = {
        kind: kind.includes("primary")
          ? "primary"
          : kind.includes("foreign")
            ? "foreign"
            : kind.includes("unique")
              ? "unique"
              : kind.includes("check")
                ? "check"
                : "index",
        name: def.constraint ?? def.index ?? undefined,
        columns: columns(def.definition),
      };
      if (c.kind === "check") {
        c.columns = [];
        try {
          c.expression = expression(def.definition?.[0] ?? def.expr);
        } catch {
          model.diagnostics.push({
            severity: "warning",
            code: "unsupportedMetadata",
            detail: "CHECK",
          });
          continue;
        }
      }
      if (def.reference_definition) {
        const r = def.reference_definition;
        c.reference = {
          table: name(r.table[0].table),
          schema: r.table[0].db ?? undefined,
          columns: columns(r.definition),
          actions: r.on_action
            ?.map((x: Ast) => Object.values(x).join(" "))
            .join(" "),
        };
      }
      t.constraints.push(c);
    }
    for (const pk of t.constraints.filter((c) => c.kind === "primary"))
      for (const c of t.columns)
        if (pk.columns.includes(c.name)) {
          c.primaryKey = true;
          c.nullable = false;
        }
    if (!t.columns.length)
      model.diagnostics.push({
        severity: "error",
        code: "unsupported",
        detail: "Empty table",
      });
    for (const opt of a.table_options ?? []) {
      if (opt.keyword?.toLowerCase() === "comment")
        t.comment = String(opt.value)
          .replace(/^'|'$/g, "")
          .replaceAll("''", "'");
      else
        model.diagnostics.push({
          severity: "warning",
          code: "unsupportedMetadata",
          detail: t.name + " table options (preserved in metadata)",
        });
    }
    assignNames(t);
    model.tables.push(t);
  }
  for (const a of statements) {
    if (a.type === "comment") {
      const ref = a.target?.name;
      const t = model.tables.find(
        (t) =>
          t.name === ref?.table &&
          (t.schema ?? "") === (ref?.db ?? ref?.schema ?? ""),
      );
      if (!t) {
        model.diagnostics.push({
          severity: "error",
          code: "unsupported",
          detail: "COMMENT target",
        });
        continue;
      }
      if (a.target.type === "table") t.comment = a.expr?.expr?.value;
      else {
        const c = t.columns.find((c) => c.name === name(ref.column));
        if (c) c.comment = a.expr?.expr?.value;
        else
          model.diagnostics.push({
            severity: "error",
            code: "unsupported",
            detail: "COMMENT column",
          });
      }
    }
    if (a.type === "create" && a.keyword === "index") {
      const t = model.tables.find(
        (t) =>
          t.name === a.table?.table && (t.schema ?? "") === (a.table?.db ?? ""),
      );
      if (
        !t ||
        a.where ||
        a.include ||
        a.index_columns?.some(
          (x: Ast) => x.type !== "column_ref" || x.order_by || x.opclass,
        )
      ) {
        model.diagnostics.push({
          severity: "error",
          code: "unsupported",
          detail: "INDEX",
        });
        continue;
      }
      t.constraints.push({
        kind: a.index_type?.toUpperCase() === "UNIQUE" ? "unique" : "index",
        name: a.index,
        columns: columns(a.index_columns),
      });
    }
  }
  return model;
}
